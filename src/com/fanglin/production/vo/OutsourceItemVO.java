package com.fanglin.production.vo;

public class OutsourceItemVO {

	private Long oiid;

	private Long oid;

	private String name;

	private Float height;

	private Float width;

	private Float thick;

	private String modelling;

	private Float num;

	private Float unitprice;

	private Long total;

	private String comment;

	public OutsourceItemVO() {
		super();
	}

	public Long getOiid() {
		return oiid;
	}

	public void setOiid(Long oiid) {
		this.oiid = oiid;
	}

	public Long getOid() {
		return oid;
	}

	public void setOid(Long oid) {
		this.oid = oid;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public Float getHeight() {
		return height;
	}

	public void setHeight(Float height) {
		this.height = height;
	}

	public Float getWidth() {
		return width;
	}

	public void setWidth(Float width) {
		this.width = width;
	}

	public Float getThick() {
		return thick;
	}

	public void setThick(Float thick) {
		this.thick = thick;
	}

	public String getModelling() {
		return modelling;
	}

	public void setModelling(String modelling) {
		this.modelling = modelling;
	}

	public Float getNum() {
		return num;
	}

	public void setNum(Float num) {
		this.num = num;
	}

	public Float getUnitprice() {
		return unitprice;
	}

	public void setUnitprice(Float unitprice) {
		this.unitprice = unitprice;
	}

	public Long getTotal() {
		return total;
	}

	public void setTotal(Long total) {
		this.total = total;
	}

	public String getComment() {
		return comment;
	}

	public void setComment(String comment) {
		this.comment = comment;
	}

}
