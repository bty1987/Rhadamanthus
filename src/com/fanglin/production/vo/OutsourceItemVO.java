package com.fanglin.production.vo;

public class OutsourceItemVO {

	private Long oiid;

	private Long oid;

	private String name;

	private Integer height;

	private Integer width;

	private Integer thick;

	private String modelling;

	private Integer num;

	private Integer unitprice;

	private Long total;

	private String comment;

	public OutsourceItemVO() {
		super();
	}

	public Long getOiid() {
		return oiid;
	}

	public void setOiid(Long oiid) {
		this.oiid = oiid;
	}

	public Long getOid() {
		return oid;
	}

	public void setOid(Long oid) {
		this.oid = oid;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public Integer getHeight() {
		return height;
	}

	public void setHeight(Integer height) {
		this.height = height;
	}

	public Integer getWidth() {
		return width;
	}

	public void setWidth(Integer width) {
		this.width = width;
	}

	public Integer getThick() {
		return thick;
	}

	public void setThick(Integer thick) {
		this.thick = thick;
	}

	public String getModelling() {
		return modelling;
	}

	public void setModelling(String modelling) {
		this.modelling = modelling;
	}

	public Integer getNum() {
		return num;
	}

	public void setNum(Integer num) {
		this.num = num;
	}

	public Integer getUnitprice() {
		return unitprice;
	}

	public void setUnitprice(Integer unitprice) {
		this.unitprice = unitprice;
	}

	public Long getTotal() {
		return total;
	}

	public void setTotal(Long total) {
		this.total = total;
	}

	public String getComment() {
		return comment;
	}

	public void setComment(String comment) {
		this.comment = comment;
	}

}
