CREATE DATABASE  IF NOT EXISTS `material`;
USE `material`;

DROP TABLE IF EXISTS `material`;
CREATE TABLE `material` (
  `mid` int(11) NOT NULL AUTO_INCREMENT,
  `no` varchar(15) NOT NULL,
  `orderId` varchar(15) NOT NULL,
  `hid` int(11) NOT NULL,
  `customerId` int(11) NOT NULL,
  `smuid` int(11) NOT NULL COMMENT '业务员ID',
  `muid` int(11) NOT NULL COMMENT '主材员ID',
  `iuid` int(11) DEFAULT NULL COMMENT '驻店员ID',
  `category` varchar(32) NOT NULL DEFAULT '',
  `brand` varchar(32) NOT NULL DEFAULT '',
  `packageFlag` tinyint(4) NOT NULL DEFAULT '0',
  `rid` varchar(11) NOT NULL COMMENT '业务分区ID',
  `did` varchar(11) NOT NULL COMMENT '业务部门ID',
  `mdid` varchar(11) NOT NULL COMMENT '主材部ID',
  `createTime` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `preBalanceTime` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `postBalanceTime` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `type` tinyint(1) DEFAULT '0',
  `status` tinyint(1) DEFAULT '0' COMMENT '初始, 删除',
  `depositPayment` decimal(10,3) NOT NULL DEFAULT '0.000',
  `depositStatus` tinyint(1) NOT NULL DEFAULT '0',
  `fullPayment` decimal(10,3) NOT NULL DEFAULT '0.000',
  `fullStatus` tinyint(1) NOT NULL DEFAULT '0',
  `balanceStatus` tinyint(1) NOT NULL DEFAULT '0',
  `total` decimal(10,3) NOT NULL DEFAULT '0.000',
  `distotal` decimal(10,3) NOT NULL DEFAULT '0.000' COMMENT '折扣总价',
  `maling` decimal(10,3) NOT NULL DEFAULT '0.000',
  `venderMaling` decimal(10,3) NOT NULL DEFAULT '0.000',
  `coupon` decimal(10,3) NOT NULL DEFAULT '0.000',
  `couponInfo` varchar(64) NOT NULL DEFAULT '',
  `comment` varchar(256) NOT NULL DEFAULT '',
  `fullpayTime` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `otherStatus` tinyint(1) NOT NULL DEFAULT '0',
  `company` int(11) NOT NULL,
  PRIMARY KEY (`mid`),
  KEY `indexone` (`orderId`,`status`),
  KEY `indextwo` (`balanceStatus`,`fullStatus`),
  KEY `indexthr` (`no`),
  KEY `indexsix` (`status`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8 COMMENT='主材单表';

DROP TABLE IF EXISTS `materialbalance`;
CREATE TABLE `materialbalance` (
  `mbid` int(11) NOT NULL AUTO_INCREMENT,
  `mid` int(11) NOT NULL,
  `cuid` int(11) NOT NULL COMMENT ' 创建人ID',
  `iuid` int(11) DEFAULT NULL COMMENT '主材驻店ID',
  `puid` int(11) DEFAULT NULL COMMENT '结算人ID',
  `balanceTime` timestamp NULL DEFAULT NULL COMMENT '预结算时间',
  `balance` decimal(10,3) NOT NULL DEFAULT '0.000',
  `difference` decimal(10,3) NOT NULL DEFAULT '0.000',
  `vbalance` decimal(10,3) NOT NULL DEFAULT '0.000',
  `vbalanceTime` timestamp NULL DEFAULT NULL COMMENT '厂商结算时间',
  `post` decimal(10,3) NOT NULL DEFAULT '0.000',
  `postTime` timestamp NULL DEFAULT NULL COMMENT '结算时间',
  `total` decimal(10,3) NOT NULL DEFAULT '0.000',
  `status` tinyint(4) NOT NULL DEFAULT '0',
  `type` tinyint(4) NOT NULL DEFAULT '0',
  `ident` int(11) NOT NULL DEFAULT '0',
  `mpid` int(11) DEFAULT NULL,
  PRIMARY KEY (`mbid`),
  KEY `indexone` (`mid`),
  KEY `indextwo` (`balanceTime`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8 COMMENT='主材单结算表';

DROP TABLE IF EXISTS `materialitem`;
CREATE TABLE `materialitem` (
  `miid` int(11) NOT NULL AUTO_INCREMENT,
  `mid` int(11) NOT NULL,
  `no` varchar(64) NOT NULL,
  `name` varchar(64) NOT NULL,
  `category` varchar(32) NOT NULL DEFAULT '',
  `brand` varchar(32) NOT NULL DEFAULT '',
  `measurementUnit` varchar(10) NOT NULL,
  `packageName` varchar(10) NOT NULL DEFAULT '',
  `unitPrice` decimal(10,3) NOT NULL,
  `purchasePrice` decimal(10,3) NOT NULL,
  `salePrice` decimal(10,3) NOT NULL DEFAULT '0.000',
  `price` decimal(10,3) NOT NULL DEFAULT '0.000',
  `discount` decimal(10,3) NOT NULL DEFAULT '1.000',
  `postDiscount` decimal(10,3) NOT NULL DEFAULT '1.000',
  `num` decimal(10,3) DEFAULT '0.000',
  `total` decimal(10,3) NOT NULL DEFAULT '0.000',
  `status` tinyint(4) NOT NULL DEFAULT '0',
  `balanceStatus` tinyint(4) NOT NULL DEFAULT '0',
  `refundStatus` tinyint(4) NOT NULL DEFAULT '0',
  `calcType` tinyint(4) NOT NULL DEFAULT '0',
  `prePoint` decimal(10,3) NOT NULL DEFAULT '0.000',
  `postPoint` decimal(10,3) NOT NULL DEFAULT '0.000',
  `rawCalcType` tinyint(4) NOT NULL DEFAULT '0',
  `rawPoint` decimal(10,3) NOT NULL DEFAULT '0.000',
  `comment` varchar(256) DEFAULT '',
  PRIMARY KEY (`miid`),
  KEY `indextwo` (`mid`,`status`,`refundStatus`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8 COMMENT='主材单项表';


DROP TABLE IF EXISTS `materialrefund`;
CREATE TABLE `materialrefund` (
  `mrid` int(11) NOT NULL AUTO_INCREMENT,
  `mid` int(11) NOT NULL,
  `miid` int(11) NOT NULL,
  `mpId` int(11) NOT NULL,
  `ident` int(11) NOT NULL,
  `no` varchar(64) NOT NULL,
  `name` varchar(64) NOT NULL,
  `category` varchar(32) NOT NULL DEFAULT '',
  `brand` varchar(32) NOT NULL DEFAULT '',
  `measurementUnit` varchar(10) NOT NULL,
  `packageName` varchar(10) NOT NULL DEFAULT '',
  `unitPrice` decimal(10,3) NOT NULL,
  `purchasePrice` decimal(10,3) NOT NULL,
  `salePrice` decimal(10,3) NOT NULL DEFAULT '0.000',
  `price` decimal(10,3) NOT NULL DEFAULT '0.000',
  `discount` decimal(10,3) NOT NULL DEFAULT '1.000',
  `postDiscount` decimal(10,3) NOT NULL DEFAULT '1.000',
  `num` decimal(10,3) NOT NULL DEFAULT '0.000',
  `total` decimal(10,3) NOT NULL DEFAULT '0.000',
  `status` tinyint(4) NOT NULL DEFAULT '0',
  `balanceType` tinyint(1) NOT NULL DEFAULT '0',
  `prePoint` decimal(10,3) NOT NULL DEFAULT '0.000',
  `comment` varchar(256) DEFAULT '',
  PRIMARY KEY (`mrid`),
  KEY `indexone` (`mid`,`status`),
  KEY `indextwo` (`mpId`,`status`)
) ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=utf8 COMMENT='主材单退款信息表';


