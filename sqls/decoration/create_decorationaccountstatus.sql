CREATE TABLE IF NOT EXISTS `decoration`.`decorationaccountstatus` (
  `dasid` int(11) NOT NULL AUTO_INCREMENT,
  `orderId` varchar(15) NOT NULL COMMENT '订单编号',
  `company` int(11) NOT NULL COMMENT '公司ID',
  `status` tinyint(1) NOT NULL DEFAULT 2 COMMENT '总体状态, 0:未通过, 1:通过, 2:不验证',
  `signStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '签约指标',
  `salesStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '销售完结指标',
  `constructionStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '工程节点指标',
  `selectionStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '选材完结指标',
  `decorationPaymentStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '装修款比例指标',
  `salesPaymentStatus` tinyint(1) NOT NULL DEFAULT 2 COMMENT '销售比例指标',
  `decorationPaymentScale` tinyint(3) NOT NULL DEFAULT 0 COMMENT '装修款当前比例',
  `decorationPaymentTarget` tinyint(3) NOT NULL DEFAULT 0 COMMENT '装修款目标比例',
  `salesPaymentScale` tinyint(3) NOT NULL DEFAULT 0 COMMENT '销售当前比例',
  `salesPaymentTarget` tinyint(3) NOT NULL DEFAULT 0 COMMENT '销售目标比例',
  `constructionCnid` int(11) NOT NULL DEFAULT 0 COMMENT '工程决算节点ID',
  `constructionName` varchar(32) NOT NULL DEFAULT '' COMMENT '工程决算节点名称',
  `salesUnfinish` int(11) NOT NULL DEFAULT 0 COMMENT '未完结销售单数',
  `selectionUnfinish` int(11) NOT NULL DEFAULT 0 COMMENT '未完结选材项数',
  `updateTime` timestamp NULL COMMENT '更新时间',
  `comment` varchar(128) NOT NULL DEFAULT '',
  PRIMARY KEY (`dasid`),
  UNIQUE KEY `uniqueone` (`orderId`) USING BTREE,
  KEY `indexone` (`company`) USING BTREE,
  KEY `indextwo` (`status`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8_general_ci ROW_FORMAT=Compact COMMENT='装修决算指标表';
