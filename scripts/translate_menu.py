def translate(name):
    """翻译单个 name,返回 (en, tw)"""
    if name in DICT:
        return DICT[name]
    if name in MANUAL_DICT:
        return MANUAL_DICT[name]
    # 兜底:保留原文(标记待人工)
    return (name, name)


def main():
    load_dict()
    # 把 MANUAL_DICT 也并入 DICT(MANUAL_DICT 优先级更高)
    for k, v in MANUAL_DICT.items():
        DICT[k] = v

    data = json.load(open(os.path.join(ROOT, 'module_data.json'), 'r', encoding='utf-8'))
    print('加载菜单数据: %d 条' % len(data))

    # 统计翻译命中率
    hit = 0; miss = set()
    cn_out = {}
    en_out = {}
    tw_out = {}
    miss_examples = []

    for d in data:
        mid = d['mid']; name = d['name']
        en, tw = translate(name)
        if name in DICT:
            hit += 1
        else:
            miss.add(name)
            if len(miss_examples) < 30:
                miss_examples.append('  mid=%d %s → %s' % (mid, name, en))
        # key = menu.mid.{mid}
        k = 'menu.mid.' + str(mid)
        cn_out[k] = name
        en_out[k] = en
        tw_out[k] = tw

    print('翻译命中: %d/%d = %.1f%%' % (hit, len(data), hit*100/len(data)))
    print('未命中 name: %d 种' % len(miss))
    if miss_examples:
        print('未命中示例:')
        for s in miss_examples: print(s)

    # 写入 menu-{cn,en,tw}.json,保留 menu.code.* 部分
    for lang, out in [('cn', cn_out), ('en', en_out), ('tw', tw_out)]:
        path = os.path.join(WC, 'js', 'i18n', 'menu-%s.json' % lang)
        # 读取现有 menu.code.*
        existing = {}
        if os.path.exists(path):
            with open(path, 'r', encoding='utf-8') as f:
                existing = json.load(f)
        # 移除旧 menu.mid.*
        existing = {k: v for k, v in existing.items() if not k.startswith('menu.mid.')}
        # 合并新 mid 映射
        existing.update(out)
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(existing, f, ensure_ascii=False, indent=2)
        print('写入 %s: %d key' % (path, len(existing)))


if __name__ == '__main__':
    main()
