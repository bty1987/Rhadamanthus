import json
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WC = os.path.join(ROOT, 'WebContent')

# 词典:中文→(英文,繁体)
DICT = {}

def load_dict():
    """加载所有已有 i18n 包,构建中文→(en,tw) 词典"""
    files = []
    for d in ['js/i18n', 'js/i18n/page']:
        full = os.path.join(WC, d)
        if os.path.isdir(full):
            for f in os.listdir(full):
                if f.endswith('.json'):
                    files.append(os.path.join(full, f))

    cn_map = {}  # key→中文
    en_map = {}
    tw_map = {}
    for f in files:
        lang = 'cn' if '-cn.json' in f else ('en' if '-en.json' in f else ('tw' if '-tw.json' in f else None))
        if not lang: continue
        with open(f, 'r', encoding='utf-8') as fp:
            try: data = json.load(fp)
            except: continue
        for k, v in data.items():
            if k.startswith('_') or not isinstance(v, str): continue
            if lang == 'cn': cn_map[k] = v
            elif lang == 'en': en_map[k] = v
            elif lang == 'tw': tw_map[k] = v

    # 按 key 合并成 中文→(en,tw)
    for k, cn in cn_map.items():
        en = en_map.get(k, cn)
        tw = tw_map.get(k, cn)
        DICT[cn] = (en, tw)

