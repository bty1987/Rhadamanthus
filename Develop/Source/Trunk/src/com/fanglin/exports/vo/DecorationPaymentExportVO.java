package com.fanglin.exports.vo;

import java.io.Serializable;
import java.sql.Timestamp;

public class DecorationPaymentExportVO implements Serializable {

	private static final long serialVersionUID = 4107241515396957257L;

	private String orderId;
	
	private String village;
	
	private String houseNumber;
	
	private String designer;
	
	private String designerDepartment;
	
	private String paymentType;
	
	private Float referMoney;
	
	private Float coupon;
	
	private String couponInfo;
	
	private Timestamp collectTime;

	public String getOrderId() {
		return orderId;
	}

	public void setOrderId(String orderId) {
		this.orderId = orderId;
	}

	public String getVillage() {
		return village;
	}

	public void setVillage(String village) {
		this.village = village;
	}

	public String getHouseNumber() {
		return houseNumber;
	}

	public void setHouseNumber(String houseNumber) {
		this.houseNumber = houseNumber;
	}

	public String getDesigner() {
		return designer;
	}

	public void setDesigner(String designer) {
		this.designer = designer;
	}

	public String getDesignerDepartment() {
		return designerDepartment;
	}

	public void setDesignerDepartment(String designerDepartment) {
		this.designerDepartment = designerDepartment;
	}

	public String getPaymentType() {
		return paymentType;
	}

	public void setPaymentType(String paymentType) {
		this.paymentType = paymentType;
	}

	public Float getReferMoney() {
		return referMoney;
	}

	public void setReferMoney(Float referMoney) {
		this.referMoney = referMoney;
	}

	public Float getCoupon() {
		return coupon;
	}

	public void setCoupon(Float coupon) {
		this.coupon = coupon;
	}

	public String getCouponInfo() {
		return couponInfo;
	}

	public void setCouponInfo(String couponInfo) {
		this.couponInfo = couponInfo;
	}

	public Timestamp getCollectTime() {
		return collectTime;
	}

	public void setCollectTime(Timestamp collectTime) {
		this.collectTime = collectTime;
	}
	
}
